_CITY_BY_NORMALIZED_NAME = {
    " ".join(city.lower().replace("ё", "е").split()): city
    for city in EVENT_CITIES
}


def canonical_city(value: Optional[str]) -> Optional[str]:
    if value is None:
        return None

    normalized = " ".join(value.strip().lower().replace("ё", "е").split())
    if not normalized:
        return None

    return _CITY_BY_NORMALIZED_NAME.get(normalized)
